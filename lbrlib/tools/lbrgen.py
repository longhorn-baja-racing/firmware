#!/usr/bin/env python3
"""lbrgen: build a car's LBRLib catalog from one TOML file.

    python3 lbrlib/tools/lbrgen.py car/catalog.toml           # write the generated files
    python3 lbrlib/tools/lbrgen.py car/catalog.toml --check   # fail if any is out of date

The catalog file declares every node, signal, and CAN data frame once (its
header documents the format). From it this tool writes, next to the TOML:

    catalog/include/lbr/signals.def          signal catalog (LBR_SIGNAL rows)
    catalog/include/lbr/catalog_nodes.def    node ids, names, roles (LBR_NODE rows)
    catalog/include/lbr/catalog_frames.def   CAN data frame table (LBR_FRAME / LBR_FIELD rows)
    catalog/include/lbr/catalog_links.def    LoRa subset and cockpit display list
    catalog/include/lbr/catalog.h            node id limits
    nodes/<app>/main/<app>_plan.[ch]         each firmware's acquisition plan

and the generated tables of docs/can-ids.md (between lbrgen markers), if
that file exists. The .def files are X-macro data: LBRLib's protocol code
expands them, so the library itself stays free of car-specific names.

Every rule the firmware checks at run time or in test_plans that can be
checked here is checked here first, with a message naming the entry.
Standard library only (Python 3.11+, tomllib).
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

ENC_SIZE = {"i16": 2, "u16": 2, "u8": 1, "i32": 4, "u32": 4}
TYPES = ("f32", "i32", "u32", "bool", "status")
UNITS = (
    "none", "m_per_s2", "rad_per_s", "deg_c", "rpm", "m_per_s", "percent", "deg_e7",
    "meter", "degree", "count", "microstrain", "unix_s", "bitmask",
)
UNIT_TEXT = {
    "none": "", "m_per_s2": "m/s^2", "rad_per_s": "rad/s", "deg_c": "degC", "rpm": "rpm",
    "m_per_s": "m/s", "percent": "%", "deg_e7": "deg*1e-7", "meter": "m", "degree": "deg",
    "count": "count", "microstrain": "ue", "unix_s": "unix_s", "bitmask": "bitmask",
}
ROLES = ("central", "cockpit")
# How a slot is read (slot "input"); the role binds these itself.
INPUTS = {"io": "LBR_INPUT_IO", "gps": "LBR_INPUT_GPS", "cockpit_link": "LBR_INPUT_COCKPIT_LINK"}
CENTRAL_ONLY_INPUTS = ("gps", "cockpit_link")
DATA_ID_MIN, DATA_ID_MAX = 0x100, 0x6FF  # docs/can-ids.md: system ids sit outside
COUNTER_OFFSET, COUNTER_DLC = 6, 8
MAX_FIELDS = 8
SLOT_MAX_FRAMES = 4  # LBR_NODE_SLOT_MAX_FRAMES in lbr/node.h
DEFAULT_HEALTH_MS = 1000

GENERATED = "Generated by lbrlib/tools/lbrgen.py from {src}. Do not edit; edit {src}."


class CatalogError(Exception):
    pass


@dataclass
class Signal:
    name: str
    id: int
    type: str
    unit: str
    desc: str
    frame: Frame | None = None


@dataclass
class Field:
    signal: Signal
    offset: int
    enc: str
    scale: float


@dataclass
class Frame:
    id: int
    name: str
    sender: Node
    slot: str
    rate_hz: int
    counter: bool
    fields: list[Field]

    @property
    def dlc(self) -> int:
        if self.counter:
            return COUNTER_DLC
        return sum(ENC_SIZE[f.enc] for f in self.fields)


@dataclass
class Slot:
    name: str
    rate_hz: int
    signals: list[Signal]
    input: str | None = None  # "io", "gps", "cockpit_link", or None (bound in main.c)
    hint: str = ""            # what is usually wired to an io slot (menuconfig help)


@dataclass
class Node:
    name: str
    id: int
    board: str
    about: str
    link: str
    role: str | None
    app: str
    listen_all: bool
    health_period_ms: int
    raw_slots: list
    slots: list[Slot] = field(default_factory=list)


@dataclass
class Catalog:
    src: str
    can_max: int
    nodes: list[Node]
    signals: list[Signal]
    frames: list[Frame]
    lora: list[tuple[Signal, int]]
    cockpit: list[Signal]


# --------------------------------------------------------------------------------------
# Loading and validation


def _need(table: dict, key: str, what: str):
    if key not in table:
        raise CatalogError(f"{what}: missing '{key}'")
    return table[key]


def _ident(name: str, what: str, upper: bool) -> str:
    ok = name.replace("_", "").isalnum() and name[0].isalpha() and name.isascii()
    if not ok or (upper and name != name.upper()) or (not upper and name != name.lower()):
        case = "UPPER_CASE" if upper else "lower_case"
        raise CatalogError(f"{what}: '{name}' must be a {case} identifier")
    return name


def load(path: Path) -> Catalog:
    try:
        data = tomllib.loads(path.read_text(encoding="ascii"))
    except UnicodeDecodeError as e:
        raise CatalogError(f"{path}: not ASCII ({e})") from None
    except tomllib.TOMLDecodeError as e:
        raise CatalogError(f"{path}: {e}") from None

    can_max = int(_need(data, "can_max", "catalog"))

    # Nodes
    nodes: list[Node] = []
    for name, t in _need(data, "node", "catalog").items():
        what = f"node.{name}"
        _ident(name, what, upper=False)
        nid = int(_need(t, "id", what))
        role = t.get("role")
        if role is not None and role not in ROLES:
            raise CatalogError(f"{what}: role must be one of {ROLES}")
        if not 1 <= nid <= 254:
            raise CatalogError(f"{what}: id {nid} outside 1..254")
        on_can = role != "cockpit"
        if on_can and nid > can_max:
            raise CatalogError(f"{what}: CAN node id {nid} above can_max {can_max}")
        if not on_can and nid <= can_max:
            raise CatalogError(f"{what}: the cockpit is off the bus; give it an id above {can_max}")
        health_ms = int(t.get("health_period_ms", DEFAULT_HEALTH_MS))
        if not 100 <= health_ms <= 4000:
            raise CatalogError(f"{what}: health_period_ms {health_ms} outside 100..4000 "
                               "(the heartbeat task feeds the 5 s task watchdog)")
        nodes.append(Node(
            name=name, id=nid, board=str(t.get("board", "")), about=str(t.get("about", "")),
            link=str(t.get("link", "CAN" if on_can else "WiFi")), role=role,
            app=_ident(str(t.get("app", name)), f"{what}.app", upper=False),
            listen_all=bool(t.get("listen_all", False)),
            health_period_ms=health_ms,
            raw_slots=list(t.get("slots", [])),
        ))
    nodes.sort(key=lambda n: n.id)
    _unique([n.id for n in nodes], "node id")
    for role in ROLES:
        holders = [n.name for n in nodes if n.role == role]
        if role == "central" and len(holders) != 1:
            raise CatalogError(f"exactly one node needs role = \"central\" (found {holders})")
        if len(holders) > 1:
            raise CatalogError(f"at most one node may have role = \"{role}\" (found {holders})")
    by_node = {n.name: n for n in nodes}

    # Signals (frame fields and standalone)
    signals: list[Signal] = []

    def make_signal(t: dict, what: str) -> Signal:
        name = _ident(str(_need(t, "name", what)), what, upper=True)
        what = f"{what} {name}"
        sid = int(_need(t, "id", what))
        typ = str(t.get("type", "f32"))
        unit = str(_need(t, "unit", what))
        if not 0 < sid <= 0xFFFF:
            raise CatalogError(f"{what}: id 0x{sid:04X} outside 0x0001..0xFFFF")
        if typ not in TYPES:
            raise CatalogError(f"{what}: type '{typ}' is not one of {TYPES}")
        if unit not in UNITS:
            raise CatalogError(f"{what}: unit '{unit}' is not one of {UNITS}")
        s = Signal(name, sid, typ, unit, str(_need(t, "desc", what)))
        signals.append(s)
        return s

    frames: list[Frame] = []
    for i, t in enumerate(data.get("frame", [])):
        what = f"frame #{i + 1}"
        name = _ident(str(_need(t, "name", what)), what, upper=True)
        what = f"frame {name}"
        fid = int(_need(t, "id", what))
        sender_name = str(_need(t, "sender", what))
        if sender_name not in by_node:
            raise CatalogError(f"{what}: unknown sender '{sender_name}'")
        sender = by_node[sender_name]
        if sender.role == "cockpit":
            raise CatalogError(f"{what}: the cockpit never transmits on CAN")
        if not DATA_ID_MIN <= fid <= DATA_ID_MAX:
            raise CatalogError(f"{what}: id 0x{fid:03X} outside the data range "
                               f"0x{DATA_ID_MIN:03X}..0x{DATA_ID_MAX:03X}")
        rate = int(_need(t, "rate_hz", what))
        if rate <= 0 or 1_000_000 % rate:
            raise CatalogError(f"{what}: rate_hz {rate} must divide 1000000")
        counter = bool(t.get("counter", False))
        fields: list[Field] = []
        offset = 0
        for ft in _need(t, "signals", what):
            s = make_signal(ft, what)
            enc = str(_need(ft, "enc", f"{what} {s.name}"))
            if enc not in ENC_SIZE:
                raise CatalogError(f"{what} {s.name}: enc '{enc}' is not one of {tuple(ENC_SIZE)}")
            scale = float(ft.get("scale", 1.0))
            if s.type != "f32" and scale != 1.0:
                raise CatalogError(f"{what} {s.name}: {s.type} signals travel unscaled (scale 1)")
            if scale <= 0:
                raise CatalogError(f"{what} {s.name}: scale must be positive")
            fields.append(Field(s, offset, enc, scale))
            offset += ENC_SIZE[enc]
        room = COUNTER_OFFSET if counter else 8
        if not fields or len(fields) > MAX_FIELDS:
            raise CatalogError(f"{what}: needs 1..{MAX_FIELDS} signals")
        if offset > room:
            raise CatalogError(f"{what}: {offset} bytes of fields do not fit in {room}"
                               + (" (bytes 6..7 hold the counter)" if counter else ""))
        frame = Frame(fid, name, sender, str(_need(t, "slot", what)), rate, counter, fields)
        for f in fields:
            f.signal.frame = frame
        frames.append(frame)
    ids = [f.id for f in frames]
    if ids != sorted(ids):
        raise CatalogError("frames must be listed in id order")
    _unique(ids, "frame id")
    _unique([f.name for f in frames], "frame name")

    for i, t in enumerate(data.get("signal", [])):
        make_signal(t, f"signal #{i + 1}")
    signals.sort(key=lambda s: s.id)
    _unique([s.id for s in signals], "signal id")
    _unique([s.name for s in signals], "signal name")
    by_signal = {s.name: s for s in signals}

    def sig(name: str, what: str) -> Signal:
        if name not in by_signal:
            raise CatalogError(f"{what}: unknown signal '{name}'")
        return by_signal[name]

    # Slots. A frame naming a slot its sender lacks is a typo: say so first.
    for f in frames:
        names = {(r if isinstance(r, str) else r.get("name")) for r in f.sender.raw_slots}
        if f.slot not in names:
            raise CatalogError(f"frame {f.name}: sender {f.sender.name} has no slot '{f.slot}' "
                               f"(its slots: {', '.join(sorted(map(str, names))) or 'none'})")
    for n in nodes:
        what = f"node.{n.name}"
        sent = [f for f in frames if f.sender is n]
        for raw in n.raw_slots:
            t = {"name": raw} if isinstance(raw, str) else raw
            sname = _ident(str(_need(t, "name", f"{what} slot")), f"{what} slot", upper=False)
            swhat = f"{what} slot {sname}"
            mine = [f for f in sent if f.slot == sname]
            if len(mine) > SLOT_MAX_FRAMES:
                raise CatalogError(f"{swhat}: {len(mine)} frames, at most {SLOT_MAX_FRAMES} "
                                   "(LBR_NODE_SLOT_MAX_FRAMES)")
            from_frames = [fl.signal for f in mine for fl in f.fields]
            if "signals" in t:
                listed = [sig(str(x), swhat) for x in t["signals"]]
                _unique([s.name for s in listed], f"{swhat} signal")
                if mine and sorted(s.id for s in listed) != sorted(s.id for s in from_frames):
                    raise CatalogError(f"{swhat}: its signals must be exactly those of its frames "
                                       f"({', '.join(f.name for f in mine)})")
            else:
                listed = from_frames
            if not listed:
                raise CatalogError(f"{swhat}: no signals (no frame names this slot)")
            rates = {f.rate_hz for f in mine}
            if len(rates) > 1:
                raise CatalogError(f"{swhat}: its frames disagree on rate_hz {sorted(rates)}")
            rate = int(t.get("rate_hz", rates.pop() if rates else 0))
            if mine and rate != mine[0].rate_hz:
                raise CatalogError(f"{swhat}: rate_hz {rate} differs from its frames")
            if rate <= 0:
                raise CatalogError(f"{swhat}: give rate_hz (no frame sets it)")
            inp = t.get("input")
            if inp is not None and inp not in INPUTS:
                raise CatalogError(f"{swhat}: input '{inp}' is not one of {tuple(INPUTS)}")
            if inp in CENTRAL_ONLY_INPUTS and n.role != "central":
                raise CatalogError(f"{swhat}: input '{inp}' is only on the central node")
            n.slots.append(Slot(sname, rate, listed, inp, str(t.get("hint", ""))))
        _unique([s.name for s in n.slots], f"{what} slot name")

    # Apps shared by several nodes must agree on slot names
    for app in sorted({n.app for n in nodes}):
        group = [n for n in nodes if n.app == app]
        shapes = {tuple(s.name for s in n.slots) for n in group}
        if len(shapes) > 1:
            raise CatalogError(f"app {app}: nodes {[n.name for n in group]} need the same slots")

    # Links
    lora = []
    for i, item in enumerate(data.get("lora", {}).get("items", [])):
        if not (isinstance(item, list) and len(item) == 2):
            raise CatalogError(f"lora.items #{i + 1}: expected [signal, min_interval_ms]")
        lora.append((sig(str(item[0]), "lora.items"), int(item[1])))
    cockpit = [sig(str(x), "cockpit.signals") for x in data.get("cockpit", {}).get("signals", [])]
    _unique([s.name for s in cockpit], "cockpit signal")

    for need in ("EVENT", "FAULT"):
        if need not in by_signal:
            raise CatalogError(f"the catalog must define the standard signal {need}")
    return Catalog(str(path.name), can_max, nodes, signals, frames, lora, cockpit)


def _unique(values: list, what: str) -> None:
    seen = set()
    for v in values:
        if v in seen:
            shown = f"0x{v:X}" if isinstance(v, int) else v
            raise CatalogError(f"duplicate {what} {shown}")
        seen.add(v)


# --------------------------------------------------------------------------------------
# Emitters


def c_float(x: float) -> str:
    r = repr(float(x))
    return (r if ("." in r or "e" in r) else r + ".0") + "f"


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def def_header(cat: Catalog, title: str, rows_doc: str) -> str:
    return (f"/*\n * {title}\n *\n * {GENERATED.format(src='car/' + cat.src)}\n *\n"
            f"{rows_doc} *\n * Intentionally no include guard: this file is expanded several times.\n */\n\n")


def emit_signals(cat: Catalog) -> str:
    out = def_header(cat, "Signal catalog: identity and metadata of every signal.",
                     " * LBR_SIGNAL(NAME, ID, TYPE, UNIT, \"description\"), sorted by id.\n")
    w = max(len(s.name) for s in cat.signals) + 1
    for s in cat.signals:
        out += (f"LBR_SIGNAL({(s.name + ',').ljust(w)} 0x{s.id:04X}, {(s.type.upper() + ',').ljust(7)} "
                f"{(s.unit.upper() + ',').ljust(12)} {c_str(s.desc)})\n")
    return out


def emit_nodes(cat: Catalog) -> str:
    out = def_header(cat, "Node identity: every node's id, name, and what it does.",
                     " * LBR_NODE(NAME, id, \"name\", \"about\"), sorted by id. Never renumber or\n"
                     " * reuse an id. Under #ifdef LBR_NODE_ROLE: LBR_NODE_ROLE(ROLE, NAME) maps a\n"
                     " * library role to the node holding it, when the names differ (RESERVED: no\n"
                     " * node holds the role).\n")
    w = max(len(n.name) for n in cat.nodes) + 1
    for n in cat.nodes:
        out += f"LBR_NODE({(n.name.upper() + ',').ljust(w)} 0x{n.id:02X}, {c_str(n.name)}, {c_str(n.about)})\n"
    out += "\n#ifdef LBR_NODE_ROLE\n"
    for role in ROLES:
        holder = next((n for n in cat.nodes if n.role == role), None)
        if holder is None:
            out += f"LBR_NODE_ROLE({role.upper()}, RESERVED)\n"
        elif holder.name != role:
            out += f"LBR_NODE_ROLE({role.upper()}, {holder.name.upper()})\n"
    out += "#endif\n"
    return out


def emit_catalog_h(cat: Catalog) -> str:
    last = max(n.id for n in cat.nodes)
    return ("#pragma once\n\n"
            f"/* {GENERATED.format(src='car/' + cat.src)} */\n\n"
            f"/* Highest CAN node id: CAN nodes are 1..LBR_NODE_CAN_MAX. */\n"
            f"#define LBR_NODE_CAN_MAX 0x{cat.can_max:02X}u\n\n"
            f"/* Highest assigned node id. */\n"
            f"#define LBR_NODE_LAST 0x{last:02X}u\n\n"
            f"/* Number of nodes in the catalog. */\n"
            f"#define LBR_NODE_COUNT {len(cat.nodes)}u\n")


def emit_frames(cat: Catalog) -> str:
    out = def_header(cat, "CAN data frame table (docs/can-ids.md), sorted by id.",
                     " * LBR_FRAME(id, \"NAME\", SENDER, rate_hz, dlc, counter_offset, n_fields)\n"
                     " * followed by n_fields LBR_FIELD(SIGNAL, offset, ENC, scale) and LBR_FRAME_END.\n"
                     " * counter_offset is LBR_FRAME_NO_COUNTER for frames without a sample counter.\n")
    for f in cat.frames:
        cnt = str(COUNTER_OFFSET) if f.counter else "LBR_FRAME_NO_COUNTER"
        out += (f"LBR_FRAME(0x{f.id:03X}, {c_str(f.name)}, {f.sender.name.upper()}, {f.rate_hz}, "
                f"{f.dlc}, {cnt}, {len(f.fields)})\n")
        for fl in f.fields:
            out += f"    LBR_FIELD({fl.signal.name}, {fl.offset}, {fl.enc.upper()}, {c_float(fl.scale)})\n"
        out += "LBR_FRAME_END\n"
    return out


def emit_links(cat: Catalog) -> str:
    out = def_header(cat, "Live link selections: the LoRa subset and the cockpit display list.",
                     " * LBR_LORA_ITEM(SIGNAL, min_interval_ms) in priority order;\n"
                     " * LBR_COCKPIT_SIGNAL(SIGNAL) in wire order.\n")
    out += "#ifdef LBR_LORA_ITEM\n"
    for s, ms in cat.lora:
        out += f"LBR_LORA_ITEM({s.name}, {ms})\n"
    out += "#endif\n\n#ifdef LBR_COCKPIT_SIGNAL\n"
    for s in cat.cockpit:
        out += f"LBR_COCKPIT_SIGNAL({s.name})\n"
    out += "#endif\n"
    return out


def emit_plan_h(cat: Catalog, app: str, group: list[Node]) -> str:
    up = app.upper()
    slots = group[0].slots
    enum = ", ".join([f"{up}_SLOT_{s.name.upper()}" for s in slots] + [f"{up}_SLOT_COUNT"])
    out = "#pragma once\n\n#include \"lbr/node.h\"\n\n"
    out += f"/* {GENERATED.format(src='car/' + cat.src)} */\n\n"
    out += f"/* Acquisition slots of the {app} firmware. Unbound slots report NOT_FITTED. */\n"
    out += f"enum {{ {enum} }};\n\n"
    if len(group) == 1:
        out += f"extern const lbr_node_plan_t lbr_plan_{app};\n"
    else:
        out += "/* One plan per node running this firmware, in id order:\n"
        out += "".join(f" * [{i}] {n.name}\n" for i, n in enumerate(group)) + " */\n"
        out += f"extern const lbr_node_plan_t lbr_plan_{app}[{len(group)}];\n"
    return out


def _wrap_list(items: list[str], indent: str, width: int = 100) -> list[str]:
    lines, cur = [], indent
    for it in items:
        piece = it + ","
        if cur.strip() and len(cur) + 1 + len(piece) > width:
            lines.append(cur.rstrip())
            cur = indent
        cur += (" " if cur.strip() else "") + piece
    if cur.strip():
        lines.append(cur.rstrip())
    return lines


def emit_plan_c(cat: Catalog, app: str, group: list[Node]) -> str:
    up = app.upper()
    out = f"#include \"{app}_plan.h\"\n\n#include \"lbr/nodes.h\"\n\n"
    io = [s for s in group[0].slots if s.input == "io"]
    if io:
        out += ("/* io slots read their input spec from menuconfig (main/Kconfig, generated);\n"
                " * host builds have no sdkconfig and see an empty spec. */\n"
                "#if __has_include(\"sdkconfig.h\")\n#include \"sdkconfig.h\"\n#endif\n")
        for s in io:
            k = f"CONFIG_LBR_IO_{s.name.upper()}"
            out += f"#ifndef {k}\n#define {k} \"\"\n#endif\n"
        out += "\n"
    out += f"/*\n * {GENERATED.format(src='car/' + cat.src)}\n *\n"
    for n in group:
        out += f" * {n.name} (node {n.id}, {n.board}): {n.about}.\n"
    out += (" *\n * Pure data, compiled into the host tests: each slot's signals travel in frames\n"
            " * this node sends at the slot's rate, and the whole bus stays inside its budget.\n */\n\n")
    out += "/* clang-format off */\n"
    multi = len(group) > 1
    for gi, n in enumerate(group):
        sfx = f"_{n.name}" if multi else ""
        for s in n.slots:
            items = [f"LBR_SIG_{x.name}" for x in s.signals]
            one = f"static const lbr_signal_id_t k_{s.name}{sfx}[] = {{{', '.join(items)}}};"
            if len(one) <= 100:
                out += one + "\n"
            else:
                out += f"static const lbr_signal_id_t k_{s.name}{sfx}[] = {{\n"
                out += "\n".join(_wrap_list(items, "    ")) + "\n};\n"
        out += "\n"
        out += f"static const lbr_slot_t k_slots{sfx}[{up}_SLOT_COUNT] = {{\n"
        for s in n.slots:
            arr = f"k_{s.name}{sfx}"
            out += (f"    [{up}_SLOT_{s.name.upper()}] =\n        {{\n"
                    f"            .name      = {c_str(s.name)},\n"
                    f"            .signals   = {arr},\n"
                    f"            .n_signals = sizeof {arr} / sizeof {arr}[0],\n"
                    f"            .rate_hz   = {s.rate_hz},\n")
            if s.input:
                out += f"            .input     = {INPUTS[s.input]},\n"
            if s.input == "io":
                out += f"            .io_spec   = CONFIG_LBR_IO_{s.name.upper()},\n"
            out += "        },\n"
        out += "};\n\n"
    def plan_body(n: Node, sfx: str, indent: str) -> str:
        b = (f"{indent}.node_id          = LBR_NODE_{n.name.upper()},\n"
             f"{indent}.slots            = k_slots{sfx},\n"
             f"{indent}.n_slots          = {up}_SLOT_COUNT,\n"
             f"{indent}.health_period_ms = {n.health_period_ms},\n"
             f"{indent}.local_log        = false,\n"
             f"{indent}.listen_all       = {'true' if n.listen_all else 'false'},\n")
        return b
    if not multi:
        out += f"const lbr_node_plan_t lbr_plan_{app} = {{\n{plan_body(group[0], '', '    ')}}};\n"
        return out + "/* clang-format on */\n"
    else:
        out += f"const lbr_node_plan_t lbr_plan_{app}[{len(group)}] = {{\n"
        for n in group:
            out += f"    {{\n{plan_body(n, '_' + n.name, '        ')}    }},\n"
        out += "};\n"
    return out + "/* clang-format on */\n"


KCONFIG_IO_HELP = """\
            Empty = not fitted (or simulated with LBR_SENSOR_SIM). Otherwise one
            ';'-separated entry per channel using the on-chip inputs: '-',
            'adc ...', 'pulse ...', or 'din ...'. Syntax and examples are in
            lbrlib/docs/drivers.md and docs/sensors.md. The spec is the
            calibration and is recorded in every session.
"""


def emit_kconfig(cat: Catalog, app: str, group: list[Node]) -> str:
    """menuconfig settings for an app's io slots (main/Kconfig), or "" if none."""
    io = [i for i, s in enumerate(group[0].slots) if s.input == "io"]
    if not io:
        return ""
    out = (f"# {GENERATED.format(src='car/' + cat.src)}\n"
           "# Pins and calibration of the slots read by on-chip inputs (input = \"io\").\n\n"
           f"menu \"LBR {app} inputs\"\n")
    for i in io:
        s = group[0].slots[i]
        frames = sorted({x.frame.id for x in s.signals if x.frame is not None})
        where = (" (frame" + ("s " if len(frames) > 1 else " ")
                 + " and ".join(f"0x{f:03X}" for f in frames) + ")") if frames else ""
        chans = ", ".join(x.name for x in s.signals)
        others = ""
        if len(group) > 1:
            others = (f" on {group[0].name}; the matching channels on "
                      + ", ".join(n.name for n in group[1:]))
        lines = _wrap_words(f"Channels, in order: {chans}{where}{others}."
                            + (f" Typically {s.hint}." if s.hint else ""), 64)
        out += (f"\n    config LBR_IO_{s.name.upper()}\n"
                f"        string \"Slot '{s.name}' input spec\"\n"
                "        default \"\"\n        help\n"
                + "".join(f"            {ln}\n" for ln in lines) + KCONFIG_IO_HELP)
    return out + "\nendmenu\n"


def _wrap_words(text: str, width: int) -> list[str]:
    lines, cur = [], ""
    for w in text.split():
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}" if cur else w
    return lines + ([cur] if cur else [])


def emit_docs_nodes(cat: Catalog) -> str:
    out = "| Id | Node | Board | Link | What it does |\n| --- | --- | --- | --- | --- |\n"
    for n in cat.nodes:
        out += f"| 0x{n.id:02X} | `{n.name}` | {n.board} | {n.link} | {n.about} |\n"
    return out


def emit_docs_frames(cat: Catalog) -> str:
    out = ("| Id | Frame | Sender | Rate | dlc | Fields (byte: signal encoding x scale unit) | Counter |\n"
           "| --- | --- | --- | ---: | ---: | --- | --- |\n")
    for f in cat.frames:
        parts = []
        for fl in f.fields:
            unit = UNIT_TEXT[fl.signal.unit]
            scale = "" if fl.scale == 1.0 else f" x {fl.scale:g}"
            parts.append(f"{fl.offset}: {fl.signal.name} {fl.enc}{scale}{(' ' + unit) if unit else ''}")
        cnt = str(COUNTER_OFFSET) if f.counter else "-"
        out += (f"| 0x{f.id:03X} | `{f.name}` | {f.sender.name} | {f.rate_hz} | {f.dlc} | "
                f"{', '.join(parts)} | {cnt} |\n")
    return out


def splice(text: str, tag: str, body: str, where: str) -> str:
    begin, end = f"<!-- lbrgen:{tag} -->\n", f"<!-- /lbrgen:{tag} -->"
    i, j = text.find(begin), text.find(end)
    if i < 0 or j < i:
        raise CatalogError(f"{where}: markers '{begin.strip()}' ... '{end}' not found")
    return text[: i + len(begin)] + body + text[j:]


