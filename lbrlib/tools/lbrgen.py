def outputs(cat: Catalog, car: Path, repo: Path) -> dict[Path, str]:
    inc = car / "catalog" / "include" / "lbr"
    files = {
        inc / "signals.def": emit_signals(cat),
        inc / "catalog_nodes.def": emit_nodes(cat),
        inc / "catalog_frames.def": emit_frames(cat),
        inc / "catalog_links.def": emit_links(cat),
        inc / "catalog.h": emit_catalog_h(cat),
    }
    for app in sorted({n.app for n in cat.nodes}):
        group = [n for n in cat.nodes if n.app == app]
        main = car / "nodes" / app / "main"
        files[main / f"{app}_plan.h"] = emit_plan_h(cat, app, group)
        files[main / f"{app}_plan.c"] = emit_plan_c(cat, app, group)
        kconfig = emit_kconfig(cat, app, group)
        if kconfig:
            files[main / "Kconfig"] = kconfig
    doc = repo / "docs" / "can-ids.md"
    if doc.exists():
        text = doc.read_text(encoding="ascii")
        text = splice(text, "nodes", emit_docs_nodes(cat), str(doc))
        text = splice(text, "frames", emit_docs_frames(cat), str(doc))
        files[doc] = text
    for p, text in files.items():
        if not text.isascii():
            raise CatalogError(f"{p}: generated text is not ASCII (check the catalog strings)")
    return files


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("catalog", type=Path, help="the car's catalog.toml")
    ap.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    ap.add_argument("--repo", type=Path, help="repository root (default: the catalog's parent's parent)")
    args = ap.parse_args(argv)

    car = args.catalog.resolve().parent
    repo = (args.repo or car.parent).resolve()
    try:
        cat = load(args.catalog)
        files = outputs(cat, car, repo)
    except CatalogError as e:
        print(f"lbrgen: {e}", file=sys.stderr)
        return 2

    stale = []
    for p, text in files.items():
        old = p.read_text(encoding="ascii") if p.exists() else None
        if old == text:
            continue
        stale.append(p)
        if not args.check:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="ascii")
    rel = [str(p.relative_to(repo)) if p.is_relative_to(repo) else str(p) for p in stale]
    if args.check:
        if stale:
            print("lbrgen: out of date (run python3 lbrlib/tools/lbrgen.py "
                  f"{args.catalog}):\n  " + "\n  ".join(rel), file=sys.stderr)
            return 1
        print(f"lbrgen: {len(files)} generated files up to date")
        return 0
    print(f"lbrgen: {len(cat.signals)} signals, {len(cat.frames)} frames, {len(cat.nodes)} nodes; "
          + (f"wrote {', '.join(rel)}" if rel else "nothing changed"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
